def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    for name, hints in HINTS.items():
        path = REPO / "data" / "pre-scripts" / name
        cat = json.loads(path.read_text(encoding="utf-8"))
        n = 0
        for e in cat:
            h = hints.get(e.get("text_id"))
            if h and e.get("hint") != h:
                e["hint"] = h
                n += 1
        print(f"{name}: ใส่ hint {n} บรรทัด")
        if not args.dry_run:
            path.write_text(json.dumps(cat, ensure_ascii=False, indent=1) + "\n",
                            encoding="utf-8")


if __name__ == "__main__":
    main()
